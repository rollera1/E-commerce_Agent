CREATE TABLE copy_seo_generation (
    generation_id VARCHAR(36) NOT NULL,
    source_product_id VARCHAR(200) NOT NULL,
    target_market VARCHAR(2) NOT NULL,
    language VARCHAR(2) NOT NULL,
    status VARCHAR(32) NOT NULL,
    review_status VARCHAR(32) NOT NULL,
    title VARCHAR(255) NOT NULL,
    bullet_points TEXT NOT NULL,
    description TEXT NOT NULL,
    seo_title VARCHAR(70) NOT NULL,
    meta_description VARCHAR(160) NOT NULL,
    tags TEXT NOT NULL,
    agent VARCHAR(64) NOT NULL,
    agent_version VARCHAR(64) NOT NULL,
    prompt_version VARCHAR(64) NOT NULL,
    model VARCHAR(100) NOT NULL,
    duration_ms BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (generation_id),
    INDEX idx_copy_seo_generation_source_product (source_product_id),
    INDEX idx_copy_seo_generation_review_status (review_status)
);
